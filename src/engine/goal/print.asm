	movem.l	d0/a2,-(sp)
	jsr	(printz).l
	String	' ('
	adda.w	#$DC,a2
	bra.w	PrintParenNumber

PrintPlayerGoals					;Print " (" and the goals of player d0 of team a2
	movem.l	d0/a2,-(sp)
	jsr	(printz).l
	String	' ('
	adda.w	#$C0,a2

PrintParenNumber					;Print the number at d0 of a2 (1 to 3 digits) and ")"
	move.b	(a2,d0.w),d0
	ext.w	d0
	move.w	#1,d1
	cmp.w	#9,d0
	ble.w	.0
	move.w	#2,d1
	cmp.w	#$63,d0
	ble.w	.0
	move.w	#3,d1
.0
